//tc is o(d*(n+k)) where n is total elements and k is the base for ex 10
//  d is the number of digits in max element
// and sc is o(k+n) for frequency array

int main(){
    vector<ll>given={8,2,1,3,46,7,1,54,9,1,54};
    ll n=given.size();
    ll maxi=LLONG_MIN;
    for(int i=0;i<n;i++){
        if(given[i]>maxi){maxi=given[i];}
    } 
    for(ll exp=1; maxi/exp>0; exp*=10){
        vector<ll>count(10,0);
        for(int i=0;i<n;i++){
            int digit=(given[i]/exp)%10;
            count[digit]++;
        }
        for(int i=1;i<10;i++){
            count[i]+=count[i-1];
        }
        vector<ll>output(n,0);
        for(int i=n-1;i>=0;i--){
            ll digit=(given[i]/exp)%10;
            output[count[digit]-1]=given[i];
            count[digit]--;
        }
        given=output;
    }
    debug(given);
}
